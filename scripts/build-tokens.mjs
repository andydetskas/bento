// Build tokens/taos.tokens.json (DTCG) into:
//   src/styles/tokens.css  — CSS custom properties (light default, dark via [data-mode="dark"])
//   src/lib/tokens.ts      — typed values for scripts (3D scene, presets)
// No dependencies on purpose: the token file stays the single source of truth,
// and other targets (Figma variables, Framer styles) can be added as more writers here.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const src = JSON.parse(readFileSync(resolve(root, 'tokens/taos.tokens.json'), 'utf8'));

const isToken = (node) => node && typeof node === 'object' && '$value' in node;
const get = (path) => path.split('.').reduce((n, k) => n?.[k], src);

function resolveValue(value, seen = new Set()) {
  if (typeof value === 'string') {
    const ref = value.match(/^\{([^}]+)\}$/);
    if (ref) {
      if (seen.has(ref[1])) throw new Error(`Circular token reference: ${ref[1]}`);
      const target = get(ref[1]);
      if (!isToken(target)) throw new Error(`Unknown token reference: ${ref[1]}`);
      return resolveValue(target.$value, new Set([...seen, ref[1]]));
    }
  }
  return value;
}

function walk(node, path = [], out = []) {
  for (const [key, child] of Object.entries(node)) {
    if (key.startsWith('$')) continue;
    if (isToken(child)) out.push({ path: [...path, key], value: resolveValue(child.$value), type: child.$type });
    else if (child && typeof child === 'object') walk(child, [...path, key], out);
  }
  return out;
}

const cssValue = (v) => {
  if (Array.isArray(v)) {
    if (v.length === 4 && v.every((n) => typeof n === 'number')) return `cubic-bezier(${v.join(', ')})`;
    return v.map((f) => (/\s/.test(f) && !f.includes('(') ? `"${f}"` : f)).join(', ');
  }
  return String(v);
};
const varName = (path) => `--${path.join('-')}`;

const lines = ['/* Generated by scripts/build-tokens.mjs from tokens/taos.tokens.json. Do not edit. */', ':root {'];
const dark = [];

// Fluid type scale (Utopia method): --step-N clamps between the min and max viewport widths.
const sc = Object.fromEntries(Object.entries(src.scale).filter(([k]) => !k.startsWith('$')).map(([k, v]) => [k, v.$value]));
const r = (n) => +n.toFixed(4);
for (const n of sc.steps) {
  const lo = sc['min-base'] * sc['min-ratio'] ** n;
  const hi = sc['max-base'] * sc['max-ratio'] ** n;
  const slope = (hi - lo) / (sc['max-width'] - sc['min-width']);
  const intercept = lo - slope * sc['min-width'];
  const [a, b] = [Math.min(lo, hi), Math.max(lo, hi)];
  lines.push(`  --step-${n}: clamp(${r(a / 16)}rem, ${r(intercept / 16)}rem + ${r(slope * 100)}vw, ${r(b / 16)}rem);`);
}

// Leading trim (Capsize method). For an element with font-size 1em and line-height L:
//   margin-top    = over  * 1em - L/2   (pulls the top edge down to cap height)
//   margin-bottom = under * 1em - L/2   (pulls the bottom edge up to the baseline)
// where over = cap - (ascent - descent)/2 and under = (ascent - descent)/2.
for (const [fam, m] of Object.entries(src.metrics).filter(([k]) => !k.startsWith('$'))) {
  const cap = m.cap.$value, asc = m.ascent.$value, desc = m.descent.$value;
  lines.push(`  --cap-${fam}: ${r(cap)};`);
  lines.push(`  --trim-${fam}-over: ${r(cap - (asc - desc) / 2)};`);
  lines.push(`  --trim-${fam}-under: ${r((asc - desc) / 2)};`);
}

for (const t of walk(src)) {
  const [group, mode, ...rest] = t.path;
  if (group === 'scale' || group === 'metrics') continue;
  if (group === 'taos') {
    lines.push(`  ${varName(['taos', mode, ...rest])}: ${cssValue(t.value)};`);
  } else if (group === 'semantic') {
    // Semantic roles: light values on :root, dark values swapped in under [data-mode="dark"].
    const decl = `  ${varName(['color', ...rest])}: ${cssValue(t.value)};`;
    (mode === 'light' ? lines : dark).push(decl);
  } else {
    lines.push(`  ${varName(t.path)}: ${cssValue(t.value)};`);
  }
}
lines.push('}', '', '[data-mode="dark"] {', ...dark, '  color-scheme: dark;', '}', '');

// TS export: nested plain object of resolved values.
function plain(node) {
  const out = {};
  for (const [key, child] of Object.entries(node)) {
    if (key.startsWith('$')) continue;
    out[key] = isToken(child) ? resolveValue(child.$value) : plain(child);
  }
  return out;
}
const ts = `// Generated by scripts/build-tokens.mjs from tokens/taos.tokens.json. Do not edit.
export const tokens = ${JSON.stringify(plain(src), null, 2)} as const;

export type TaosHue = keyof typeof tokens.taos.light;
export type TaosStep = '600' | '500' | '400' | '300' | '200';
export const taos = (mode: 'light' | 'dark', hue: TaosHue, step: TaosStep): string =>
  tokens.taos[mode][hue][step];
`;

mkdirSync(resolve(root, 'src/styles'), { recursive: true });
mkdirSync(resolve(root, 'src/lib'), { recursive: true });
writeFileSync(resolve(root, 'src/styles/tokens.css'), lines.join('\n'));
writeFileSync(resolve(root, 'src/lib/tokens.ts'), ts);
console.log(`tokens: ${walk(src).length} tokens → src/styles/tokens.css, src/lib/tokens.ts`);
